#!/usr/bin/env python3
"""U-1437 generator for the square-free kernel windows of U1437Fast/Sieve.lean.

usage: gen_u1437.py SPAN PER_FILE END [OUTDIR]
Window 1 is lo = 1, A = 3, B = SPAN; window k >= 2 has A = B_{k-1} + 1, lo = A - 53,
B = A + SPAN - 1; every window has W = B - lo. Windows are grouped PER_FILE to a module
U1437Fast/G<j>.lean, and Chain.lean proves SqfUpTo of the last B from sqfUpTo_two.
The Q list is P10k.take 16, the primes q <= 53; sf.c found that q <= 53 covers every
N <= 1.004e9, worst odd N = 7409327 needs 53, worst even N = 35943430 needs 23.
"""
import sys, os

span, per, end = int(sys.argv[1]), int(sys.argv[2]), int(sys.argv[3])
out = sys.argv[4] if len(sys.argv) > 4 else os.path.dirname(os.path.abspath(__file__))
B2 = 31700 * 31700
wins = []
A, lo, B = 3, 1, span
while True:
    W = B - lo
    assert lo + W <= B2
    wins.append((lo, W, A, B))
    if B >= end:
        break
    A = B + 1
    lo = A - 53
    B = min(A + span - 1, end)
groups = [wins[i:i + per] for i in range(0, len(wins), per)]
hdr = "/-\nU-1437 square-free kernel windows, generated by gen_u1437.py %d %d %d.\n" \
      "AI-written Lean code, Claude, run 20261021T1603Z-28836. Binary Goldbach is OPEN.\n-/\n"
for j, g in enumerate(groups, 1):
    with open(os.path.join(out, "G%d.lean" % j), "w") as f:
        f.write(hdr % (span, per, end))
        f.write("import LeanLab.Verifications.U1437Fast.Sieve\n\nset_option Elab.async false\n\n")
        f.write("namespace LeanLab.Verifications.U1437Fast\n\nopen LeanLab.Verifications.Top50 LeanLab.Verifications.Top50.Bits\n\n")
        for (lo, W, A, B) in g:
            k = wins.index((lo, W, A, B)) + 1
            f.write("/-- Window %d: every N in [%d, %d] is q + square-free, q <= 53 prime. -/\n" % (k, A, B))
            f.write("theorem win_%d : tm %d %d %d &&& gm (sfm %d %d) (P10k.take 16) = tm %d %d %d := by\n  decide +kernel\n\n"
                    % (k, lo, A, B, lo, W, lo, A, B))
        f.write("end LeanLab.Verifications.U1437Fast\n")
with open(os.path.join(out, "Chain.lean"), "w") as f:
    f.write(hdr % (span, per, end))
    for j in range(1, len(groups) + 1):
        f.write("import LeanLab.Verifications.U1437Fast.G%d\n" % j)
    f.write("\nnamespace LeanLab.Verifications.U1437Fast\n\nopen LeanLab.Verifications.Top50 LeanLab.Verifications.Top50.Bits\n\n")
    prev, a = "sqfUpTo_two", 2
    for k, (lo, W, A, B) in enumerate(wins, 1):
        f.write("theorem sqf_w%d : SqfUpTo %d :=\n  sqf_extend (a := %d) (A := %d) (lo := %d) (W := %d) (B := %d) %s rfl\n"
                "    (by norm_num) (by norm_num [BB]) (by norm_num) q16_prime win_%d\n\n"
                % (k, B, a, A, lo, W, B, prev, k))
        prev, a = "sqf_w%d" % k, B
    f.write("/-- **Every N with 3 <= N <= %d is a prime plus a positive square-free number**, kernel checked. -/\n" % wins[-1][3])
    f.write("theorem sqfUpTo_end : SqfUpTo %d := %s\n\n" % (wins[-1][3], prev))
    f.write("end LeanLab.Verifications.U1437Fast\n")
print(len(wins), "windows,", len(groups), "files, last B", wins[-1][3])
