#!/usr/bin/env python3
"""U-1497 generator for the split square-free window chain, Verifications/U1497Split.

AI-written, Claude, run 20261022T2003Z-18. Binary Goldbach is OPEN.

usage: U1497_gen.py SPAN PER_FILE PER_CHAIN END [OUTDIR]

Same windows as U-1437 gen_u1437.py, only narrower and in more modules:
window 1 is lo = 1, A = 3, B = SPAN; window k >= 2 has A = B_{k-1} + 1, lo = A - 53,
B = min(A + SPAN - 1, END); W = B - lo. Q is the 16 primes q <= 53.

Files written:
  Core.lean     core only, NO Mathlib: copies of dup, rep, jOf, firstMul, gm, nsq, SR, sfm, tm,
                the literal list P32c of the primes below 31700 and Q16.
  W<j>.lean     core only, imports Core, PER_FILE windows `cw_k`, each `decide +kernel`.
  C<i>.lean     Mathlib, imports Bridge and its PER_CHAIN window modules W<j> and C<i-1>,
                chains `sqf_extend` through `SqfUpTo B_k`.
  Chain.lean    imports the last C<i>, states `sqfUpTo_end : SqfUpTo END`.
Bridge.lean is hand-written: it proves the Core copies equal the U1437Fast definitions.
"""
import sys, os

span, per, perc, end = (int(a) for a in sys.argv[1:5])
out = sys.argv[5] if len(sys.argv) > 5 else os.path.join(
    os.path.dirname(os.path.abspath(__file__)), "..", "Verifications", "U1497Split")
B2 = 31700 * 31700
NS = "LeanLab.Verifications.U1497Split"
HDR = ("/-\nU-1497 split square-free kernel windows, generated by AlmostPrimes/U1497_gen.py %d %d %d %d.\n"
       "AI-written Lean code, Claude, run 20261022T2003Z-18. Binary Goldbach is OPEN.\n-/\n"
       % (span, per, perc, end))

def primes_below(n):
    s = bytearray([1]) * n
    s[0] = s[1] = 0
    for i in range(2, int(n ** 0.5) + 1):
        if s[i]:
            s[i * i::i] = bytearray(len(s[i * i::i]))
    return [i for i in range(n) if s[i]]

wins = []
A, lo, B = 3, 1, span
while True:
    W = B - lo
    assert lo + W <= B2
    wins.append((lo, W, A, B))
    if B >= end:
        break
    A = B + 1
    lo = A - 53
    B = min(A + span - 1, end)

# ---- Core.lean, no imports beyond Init
P = primes_below(31700)
Q16 = P[:16]
assert Q16[-1] == 53
chunksP = [P[i:i + 1000] for i in range(0, len(P), 1000)]
parts = ""
for ci, cp in enumerate(chunksP):
    rows = [", ".join(str(p) for p in cp[i:i + 16]) for i in range(0, len(cp), 16)]
    parts += "def P32c%d : List Nat := [\n    %s]\n\n" % (ci, ",\n    ".join(rows))
core = HDR + """
/-! Core only checker definitions, no Mathlib, lab rule B3. Each is a verbatim copy of the
definition of the same name in `Top50/BitSieve.lean`, `Top50/P32.lean` or `U1437Fast/Sieve.lean`;
`Bridge.lean` proves the copies equal. -/

namespace %s.Core

def dup (s r : Nat) : Nat := r ||| (r <<< s)

def rep (d : Nat) : Nat → Nat
  | 0 => 1
  | j + 1 => dup (d * 2 ^ j) (rep d j)

def jOf (d L : Nat) : Nat := (L / d).log2 + 1

def firstMul (d t : Nat) : Nat := d * ((t + d - 1) / d)

def gm (P : Nat) : List Nat → Nat
  | [] => 0
  | q :: t => (P <<< q) ||| gm P t

def nsq (lo W : Nat) : List Nat → Nat
  | [] => 0
  | r :: t =>
    if r * r ≤ W then (rep (r * r) (jOf (r * r) W) <<< (firstMul (r * r) lo - lo)) ||| nsq lo W t
    else if firstMul (r * r) lo - lo < W then (1 <<< (firstMul (r * r) lo - lo)) ||| nsq lo W t
    else nsq lo W t

%s
/-- The %d primes below 31700, as literal lists of at most 1000. -/
def P32c : List Nat := %s

def SR (L : Nat) : List Nat := P32c.filter (fun r => r * r < L)

def sfm (lo W : Nat) : Nat := (nsq lo W (SR (lo + W)) &&& (2 ^ W - 1)) ^^^ (2 ^ W - 1)

def tm (lo A B : Nat) : Nat := (2 ^ (B - A + 1) - 1) <<< (A - lo)

/-- The 16 primes `q ≤ 53`. -/
def Q16 : List Nat := [%s]

end %s.Core
""" % (NS, parts, len(P), " ++ ".join("P32c%d" % i for i in range(len(chunksP))), ", ".join(map(str, Q16)), NS)
with open(os.path.join(out, "Core.lean"), "w") as f:
    f.write(core)

# ---- window modules, core only
groups = [list(range(i, min(i + per, len(wins)))) for i in range(0, len(wins), per)]
for j, g in enumerate(groups, 1):
    with open(os.path.join(out, "W%d.lean" % j), "w") as f:
        f.write(HDR)
        f.write("import %s.Core\n\nset_option Elab.async false\n\nnamespace %s.Core\n\n" % (NS, NS))
        for i in g:
            lo, W, A, B = wins[i]
            k = i + 1
            f.write("/-- Window %d: every N in [%d, %d] is q + square-free, q <= 53 prime. -/\n" % (k, A, B))
            f.write("theorem cw_%d : tm %d %d %d &&& gm (sfm %d %d) Q16 = tm %d %d %d := by\n  decide +kernel\n\n"
                    % (k, lo, A, B, lo, W, lo, A, B))
        f.write("end %s.Core\n" % NS)

# ---- chain modules, Mathlib through Bridge
chunks = [groups[i:i + perc] for i in range(0, len(groups), perc)]
prev, a = "sqfUpTo_two", 2
for c, ch in enumerate(chunks, 1):
    with open(os.path.join(out, "C%d.lean" % c), "w") as f:
        f.write(HDR)
        f.write("import %s.%s\n" % (NS, "Bridge" if c == 1 else "C%d" % (c - 1)))
        for g in ch:
            f.write("import %s.W%d\n" % (NS, groups.index(g) + 1))
        f.write("\nnamespace %s\n\nopen LeanLab.Verifications.U1437Fast\n\n" % NS)
        for g in ch:
            for i in g:
                lo, W, A, B = wins[i]
                k = i + 1
                f.write("theorem sqf_s%d : SqfUpTo %d :=\n  sqf_extend_core (a := %d) (A := %d) (lo := %d) (W := %d) (B := %d) %s rfl\n"
                        "    (by norm_num) (by norm_num [BB]) (by norm_num) Core.cw_%d\n\n"
                        % (k, B, a, A, lo, W, B, prev, k))
                prev, a = "sqf_s%d" % k, B
        f.write("end %s\n" % NS)
with open(os.path.join(out, "Chain.lean"), "w") as f:
    f.write(HDR)
    f.write("import %s.C%d\n\nnamespace %s\n\nopen LeanLab.Verifications.U1437Fast\n\n" % (NS, len(chunks), NS))
    f.write("/-- **Every N with 3 <= N <= %d is a prime plus a positive square-free number**, kernel checked. -/\n" % wins[-1][3])
    f.write("theorem sqfUpTo_end : SqfUpTo %d := %s\n\nend %s\n" % (wins[-1][3], prev, NS))
print(len(wins), "windows,", len(groups), "window modules,", len(chunks), "chain modules, last B", wins[-1][3])
